def included(name):
    parts = name.split("/")
    return (not name.startswith("docs/") or name in DOCUMENTS or name.endswith("/.gitattributes")
            or name.startswith("docs/implementation/20261018-evolution/evidence/backend-recovery-ci28/")
            or name.startswith("docs/") and len(parts) == 2 and name.endswith(".md")
            or name.startswith("docs/implementation/20261018-evolution/") and len(parts) == 4
            and name.endswith((".md", ".json")))


def verify_manifest(source, manifest):
    actual = subprocess.check_output(["git", "--no-replace-objects", "rev-parse", "HEAD"], cwd=source).decode().strip()
    if actual != manifest["source_commit"]:
        raise ValueError("Frozen replay HEAD differs")
    for row in manifest["files"]:
        path = source / row["path"]
        if not path.is_file() or path.is_symlink() or hashlib.sha256(path.read_bytes()).hexdigest() != row["raw_sha256"]:
            raise ValueError("Frozen replay executable source or test document differs")
    return len(manifest["files"])


def materialize(revision, destination, manifest_path):
    if re.fullmatch(r"[0-9a-f]{40}", revision) is None:
        raise ValueError("A complete frozen commit is required")
    destination = destination.absolute()
    if destination.exists() or destination.is_relative_to(ROOT) or manifest_path.exists():
        raise ValueError("Frozen replay needs new paths outside the current checkout")
    listing = subprocess.check_output(["git", "--no-replace-objects", "ls-tree", "-r", "-z", "--long", revision], cwd=ROOT)
    rows = [item.split(b"\t", 1)[0].split() for item in listing.split(b"\0") if item]
    spec = {"commit": revision, "tree": subprocess.check_output(["git", "--no-replace-objects", "rev-parse",
             revision + "^{tree}"], cwd=ROOT).decode().strip(), "files": len(rows),
            "regular_bytes": sum(int(row[3]) for row in rows)}
    complete = specification(ROOT, spec)
    selected = {name: value for name, value in complete.items() if included(name)}
    if DOCUMENTS - selected.keys():
        raise ValueError("A required web test document is absent from the frozen source")
    subprocess.run(["git", "--no-replace-objects", "worktree", "add", "--detach", "--no-checkout",
                    str(destination), revision], cwd=ROOT, env=git_environment(), check=True, capture_output=True)
    subprocess.run(["git", "--no-replace-objects", "read-tree", revision], cwd=destination,
                   env=git_environment(), check=True, capture_output=True)
    entries = {name: (oid, format(mode, "o")) for name, (mode, oid, size) in selected.items()}
    records = []
    native_frames = retained_native11()
    for name, raw, oid, mode in raw_blobs(ROOT, entries):
        git_raw_sha256 = hashlib.sha256(raw).hexdigest()
        if name in NATIVE11_GIT_LF:
            raw = original_native_helper(name, raw, native_frames)
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        with target.open("xb") as out:
            out.write(raw)
        target.chmod(int(mode, 8))
        records.append({"path": name, "git_blob": oid, "git_raw_sha256": git_raw_sha256,
                        "retained_native11_original": name in NATIVE11_GIT_LF, "bytes": len(raw),
                        "raw_sha256": hashlib.sha256(raw).hexdigest()})
    omitted = sorted(complete.keys() - selected.keys())
    subprocess.run(["git", "--no-replace-objects", "update-index", "--skip-worktree", "-z", "--stdin"],
                   input=b"\0".join(name.encode() for name in omitted) + b"\0", cwd=destination,
                   env=git_environment(), check=True, capture_output=True)
    manifest = {"scope": "All executable source and explicit test documents; historical docs omitted, no selection changes",
                "source_commit": revision, "complete_tree": spec, "files": records,
                "omitted_documentation_files": len(omitted), "dependencies_copied": False,
                "native11_original_RAW_frames_preserved": len(native_frames),
                "Desktop_product_tests_selected": False}
    verify_manifest(destination, manifest)
    with manifest_path.open("xb") as out:
        out.write((json.dumps(manifest, indent=2) + "\n").encode())
    return {"source_commit": revision, "selected_files": len(records),
            "selected_raw_bytes": sum(row["bytes"] for row in records),
            "manifest_raw_sha256": hashlib.sha256(manifest_path.read_bytes()).hexdigest()}


