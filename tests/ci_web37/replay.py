NATIVE11_ARCHIVE = "ced0218aa2a14fbf753d94e986cdaf7e33aa52df5f0e5019a0a9a16d4614c349"


def retained_native11(directory=None):
    from tests.ci_web37.native22_frames import FIXTURES, OriginalFrames
    directory = FIXTURES if directory is None else directory
    proof = OriginalFrames()
    raw = (directory / "native11-retained-originals.zip").read_bytes()
    if hashlib.sha256(raw).hexdigest() != NATIVE11_ARCHIVE:
        raise ValueError("Retained native11 finite archive differs")
    with zipfile.ZipFile(io.BytesIO(raw)) as archive:
        if archive.namelist() != list(NATIVE11_GIT_LF):
            raise ValueError("Retained native11 exact paths or order differ")
        frames = {}
        for name in NATIVE11_GIT_LF:
            record = proof.manifest["helper_union"][name]
            entry = archive.getinfo(name)
            if entry.file_size != record["bytes"]:
                raise ValueError("Retained native11 original size differs")
            frame = archive.read(name)
            if hashlib.sha256(frame).hexdigest() != record["raw_sha256"]:
                raise ValueError("Retained native11 original RAW differs")
            frames[name] = frame
    return frames


def original_native_helper(name, git_raw, frames):
    if type(name) is not str or name not in NATIVE11_GIT_LF or type(git_raw) is not bytes:
        raise ValueError("Retained native11 permits only its eleven exact paths")
    digest, size = NATIVE11_GIT_LF[name]
    if len(git_raw) != size or hashlib.sha256(git_raw).hexdigest() != digest:
        raise ValueError("Retained native11 current Git LF binding differs")
    return frames[name]

