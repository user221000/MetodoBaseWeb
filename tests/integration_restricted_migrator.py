def test_installed_historical_role_grants_are_preserved_without_rerunning_c4(owned_roles,tmp_path):
    case=owned_roles
    if case['state']!='present':pytest.skip('Exact historical grants require the pre-existing real role; absent cluster never creates it')
    from alembic import command
    clone=tmp_path/'history'
    shutil.copytree(ROOT/'web/database/alembic',clone,ignore=shutil.ignore_patterns('__pycache__','*.pyc'))
    with zipfile.ZipFile(EVIDENCE/'c4-before-exact.zip') as archive:
        (clone/'versions'/Path(MIGRATION).name).write_bytes(archive.read(MIGRATION))
    config=alembic_config();config.set_main_option('script_location',str(clone))
    with case['migrator'].begin() as db:
        config.attributes['connection']=db
        command.upgrade(config,REVISION)
    verify_runtime_schema(case['migrator'],expected_revision=REVISION)
    before=snapshot(case['migrator'])
    with case['migrator'].connect() as db:
        assert db.scalar(text("SELECT count(DISTINCT c.relname) FROM pg_class c CROSS JOIN LATERAL aclexplode(c.relacl) a WHERE c.relnamespace='public'::regnamespace AND a.grantee=(SELECT oid FROM pg_roles WHERE rolname=:role)"),{'role':LEGACY})==4
    assert cli(case).returncode==0
    assert snapshot(case['migrator'])==before


