def legacy_state(connection):
    role=connection.execute(text('SELECT oid,rolname,rolsuper,rolcreaterole,rolcreatedb,rolcanlogin,rolreplication,rolbypassrls,rolinherit,rolconfig FROM pg_roles WHERE rolname=:role'),{'role':LEGACY}).one_or_none()
    members=connection.execute(text('SELECT roleid,member,grantor,admin_option,inherit_option,set_option FROM pg_auth_members WHERE roleid=(SELECT oid FROM pg_roles WHERE rolname=:role) OR member=(SELECT oid FROM pg_roles WHERE rolname=:role) ORDER BY roleid,member,grantor'),{'role':LEGACY}).all()
    return {'role':list(role) if role else None,'memberships':[list(row) for row in members]}


