/* Synthetic browser checks. Provider responses are transport fixtures, not sandbox payments. */
const { chromium } = require('playwright-core');
const { AxeBuilder } = require('@axe-core/playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = process.env.METODOBASE_E2E_URL || 'http://127.0.0.1:8766';
if (!/^http:\/\/(127\.0\.0\.1|localhost):\d+$/.test(base)) throw Error('Only a local synthetic server is allowed');
const out = path.resolve(__dirname, '../../docs/implementation/20261018-evolution/evidence/ux');
fs.mkdirSync(out, {recursive:true});
const state = { plan:'starter', status:'active', provider:null, planes_usados:0, max_planes:1, planes_restantes:1, renovacion:'2026-11', period_end:null, cancel_at_period_end:false };
(async()=>{
  const browser = await chromium.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  const context = await browser.newContext({viewport:{width:390,height:844}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error=>errors.push(error.message));
  await context.route('**/*', route=>route.request().url().startsWith(base) ? route.continue() : route.abort());
  const response = await context.request.post(base+'/api/auth/registro',{data:{email:'browser-'+Date.now()+'@example.invalid',password:'Synthetic-Test-Password-2026!',nombre:'Browser Synthetic',tipo:'usuario'}});
  assert.equal(response.ok(),true,await response.text());
  const auth = await response.json();
  await context.addInitScript(auth=>{
    localStorage.setItem('mb_token',auth.access_token);
    localStorage.setItem('mb_refresh_token',auth.refresh_token || '');
    localStorage.setItem('mb_tipo','usuario');
    localStorage.setItem('mb_nombre','Browser Synthetic');
  },auth);
  await page.route('**/api/usuario/suscripcion',route=>route.fulfill({json:state}));
  await page.route('**/api/usuario/billing-config',route=>route.fulfill({json:{checkout_supported:true,mercadopago_configured:true,payment_link_pro:''}}));
  const checkout = [];
  let portal = 0;
  const forbidden = [];
  page.on('request',request=>{
    if (request.method()==='POST' && request.url().endsWith('/api/usuario/suscripcion')) forbidden.push(request.url());
  });
  await page.route('**/api/usuario/checkout',route=>{
    checkout.push({body:route.request().postDataJSON(),key:route.request().headers()['idempotency-key']});
    return route.fulfill({status:502,json:{detail:{code:'payment_service_unavailable',message:'El servicio de pago no está disponible. Intenta de nuevo.',request_id:'synthetic-reference'}}});
  });
  await page.route('**/api/usuario/billing-portal',route=>{
    portal++;
    return route.fulfill({status:502,json:{detail:{code:'payment_service_unavailable',message:'El portal no está disponible. Intenta de nuevo.',request_id:'synthetic-portal'}}});
  });
  const report = {scope:'Local synthetic browser; payment transport fixtures; no provider connection or payment',checks:[],viewports:[]};
  await page.goto(base+'/mi-suscripcion?result=success');
  await page.waitForFunction(()=>document.querySelector('#sub-status-badge').textContent==='Gratis');
  assert.match(await page.locator('#subscription-feedback').textContent(),/aún no aparece confirmado/);
  assert.equal(await page.locator('#sub-plan-name').textContent(),'Starter');
  report.checks.push('A success return never grants Pro or posts a plan change');
  await page.locator('#btn-pro').focus();
  await page.keyboard.press('Enter');
  await page.locator('[role=dialog]').waitFor({state:'visible'});
  assert.equal(await page.locator('#pago-modal-close').evaluate(element=>element===document.activeElement),true);
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.locator('#pago-btn-cancel').evaluate(element=>element===document.activeElement),true);
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#btn-pro').evaluate(element=>element===document.activeElement),true);
  report.checks.push('Native Enter opens provider dialog; focus trapped and restored with Escape');
  await page.locator('#btn-pro').click();
  await page.locator('#pm-card').click();
  await page.locator('#pago-btn-confirm').click();
  await page.waitForFunction(()=>document.querySelector('#payment-method-description').textContent.includes('synthetic-reference'));
  await page.locator('#pago-btn-confirm').click();
  await page.waitForFunction(()=>document.querySelector('#payment-method-description').textContent.includes('synthetic-reference'));
  assert.equal(checkout.length,2);
  assert.ok(checkout[0].key);
  assert.equal(checkout[0].key,checkout[1].key);
  assert.deepEqual(checkout[0].body,{success_url:'/mi-suscripcion?result=success',cancel_url:'/mi-suscripcion?result=canceled'});
  assert.equal(await page.locator('#sub-plan-name').textContent(),'Starter');
  report.checks.push('Checkout retry reuses Idempotency-Key; structured failure visible; access unchanged');
  const dialogAxe = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
  report.dialogViolations=dialogAxe.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}));
  await page.screenshot({path:path.join(out,'subscription-dialog-after.png'),fullPage:true});
  await page.keyboard.press('Escape');
  await page.locator('[role=dialog]').waitFor({state:'hidden'});
  for(const width of [320,390,768,1440]){
    await page.setViewportSize({width,height:900});
    const dimensions = await page.evaluate(()=>({viewport:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
    const axe = await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
    report.viewports.push({width,dimensions,violations:axe.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}))});
    await page.screenshot({path:path.join(out,'subscription-after-'+width+'.png'),fullPage:true});
  }
  state.plan='pro';state.provider='stripe';state.max_planes=5;state.period_end='2026-11-18T00:00:00Z';
  await page.locator('#btn-refresh-subscription').click();
  await page.waitForFunction(()=>document.querySelector('#sub-plan-name').textContent==='Pro');
  await page.locator('#btn-manage-subscription').click();
  await page.waitForFunction(()=>document.querySelector('#subscription-feedback').textContent.includes('synthetic-portal'));
  assert.equal(portal,1);
  assert.equal(await page.locator('#btn-starter').isDisabled(),true);
  assert.equal(forbidden.length,0);
  report.checks.push('Stripe management calls backend portal; Starter never requests a false cancellation');
  await page.route('**/api/usuario/suscripcion',route=>route.fulfill({contentType:'text/html',body:'<html>Unavailable</html>'}));
  await page.goto(base+'/mi-suscripcion');
  await page.waitForFunction(()=>document.querySelector('#subscription-feedback').textContent.includes('respuesta no válida'));
  assert.equal(await page.locator('#sub-plan-name').textContent(),'Por confirmar');
  assert.equal(await page.locator('#btn-pro').isDisabled(),true);
  await page.route('**/api/usuario/suscripcion',route=>route.fulfill({json:{}}));
  await page.locator('#btn-refresh-subscription').click();
  await page.waitForFunction(()=>document.querySelector('#subscription-feedback').textContent.includes('incompleto'));
  assert.equal(await page.locator('#sub-plan-name').textContent(),'Por confirmar');
  await page.route('**/api/usuario/suscripcion',route=>route.fulfill({json:state}));
  await page.locator('#btn-refresh-subscription').click();
  await page.waitForFunction(()=>document.querySelector('#sub-plan-name').textContent==='Pro');
  report.checks.push('HTTP200 HTML and incomplete JSON stay unknown; a valid retry recovers');
  report.errors=errors;
  report.checkoutRequests=checkout.length;
  report.forbiddenPlanMutations=forbidden.length;
  fs.writeFileSync(path.join(out,'subscription-browser.json'),JSON.stringify(report,null,2));
  assert.equal(errors.length,0,JSON.stringify(errors));
  assert.ok(report.viewports.every(v=>v.dimensions.scrollWidth<=v.width),'Horizontal overflow');
  assert.equal(report.dialogViolations.length,0,'Dialog accessibility violations');
  assert.ok(report.viewports.every(v=>v.violations.length===0),'WCAG AA automated violations');
  console.log(JSON.stringify({checks:report.checks,violations:report.viewports.map(v=>({width:v.width,count:v.violations.length})),dialogViolations:report.dialogViolations.length,errors}));
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});

