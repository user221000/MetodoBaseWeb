"""Versioned structural schema signature format v1; keep stable for migrations."""
import json
import re
from sqlalchemy import inspect

_LITERAL = r"'(?:[^']|'')*'::character varying(?:::text)?"
_TEXT_ARRAY_CHECK = re.compile(
    r"(?P<open>\()?(?P<column>[a-zA-Z_][a-zA-Z0-9_]*)::text = ANY \(ARRAY\["
    r"(?P<items>" + _LITERAL + r"(?:, " + _LITERAL + r")*)\](?P<cast>::text\[\])?\)"
    r"(?P<close>\))?(?P<nullable> OR (?P<null_column>[a-zA-Z_][a-zA-Z0-9_]*) IS NULL)?"
)
_TEXT_ARRAY_ITEM = re.compile(r"(?P<value>'(?:[^']|'')*')::character varying(?P<cast>::text)?")


def _type_attributes(column_type) -> dict:
    """Keep physical attributes that a dialect's type string can omit."""
    result = {}
    for name in ("length", "collation", "precision", "scale", "timezone", "enums", "native_enum", "name", "schema", "dimensions"):
        if hasattr(column_type, name):
            value = getattr(column_type, name)
            result[name] = list(value) if isinstance(value, (list, tuple)) else value
    if hasattr(column_type, "item_type"):
        result["item_type"] = {"type": str(column_type.item_type),
                               "attributes": _type_attributes(column_type.item_type)}
    return result


def _expression(value, schema: str | None = None):
    if value is None:
        return None
    normalized = " ".join(str(value).split())
    if schema:
        normalized = normalized.replace(schema + ".", "").replace('"' + schema + '".', "")
    # pg_dump reparses varchar literal arrays with an equivalent placement of
    # the cast to text. Normalize only this complete, literal-only predicate;
    # values, columns, null allowance and other conditions remain authority.
    match = _TEXT_ARRAY_CHECK.fullmatch(normalized)
    if match and bool(match["open"]) == bool(match["close"]) and (
            match["null_column"] is None or match["null_column"] == match["column"]):
        items = list(_TEXT_ARRAY_ITEM.finditer(match["items"]))
        if match["cast"] or all(item["cast"] for item in items):
            values = ", ".join(item["value"] + "::text" for item in items)
            normalized = (match["open"] or "") + match["column"] + "::text = ANY (ARRAY[" + values + "])" + (match["close"] or "") + (match["nullable"] or "")
    return normalized


def schema_signature(connection, *, schema: str | None = None) -> dict:
    """Describe structural schema without reading business rows or credentials.

    Constraint names generated by the database are not authority; columns,
    checks, actions and uniqueness are. Index names are retained for reproducible
    rollout/rollback. Alembic's bookkeeping table is excluded from the payload.
    """
    inspector = inspect(connection)
    result = {"dialect": connection.dialect.name, "tables": {}}
    for table in sorted(inspector.get_table_names(schema=schema)):
        if table == "alembic_version":
            continue
        columns = []
        for column in inspector.get_columns(table, schema=schema):
            columns.append({"name": column["name"], "type": str(column["type"]),
                            "type_attributes": _type_attributes(column["type"]),
                            "nullable": column["nullable"], "default": _expression(column.get("default"), schema)})
        unique = sorted([sorted(item["column_names"]) for item in inspector.get_unique_constraints(table, schema=schema)])
        foreign_keys = []
        for item in inspector.get_foreign_keys(table, schema=schema):
            foreign_keys.append({"columns": item["constrained_columns"], "table": item["referred_table"],
                                 "referred_columns": item["referred_columns"], "options": item.get("options") or {}})
        checks = [{"name": item.get("name"), "sql": _expression(item["sqltext"], schema)}
                  for item in inspector.get_check_constraints(table, schema=schema)]
        indexes = []
        for item in inspector.get_indexes(table, schema=schema):
            if item.get("duplicates_constraint"):
                continue
            options = item.get("dialect_options") or {}
            where = options.get("postgresql_where")
            if where is None:
                where = options.get("sqlite_where")
            indexes.append({"name": item["name"], "columns": item["column_names"], "unique": bool(item["unique"]),
                            "where": _expression(where, schema)})
        result["tables"][table] = {"columns": sorted(columns, key=lambda item: item["name"]),
                                  "primary_key": inspector.get_pk_constraint(table, schema=schema)["constrained_columns"],
                                  "unique": unique, "foreign_keys": sorted(foreign_keys, key=lambda item: json.dumps(item, sort_keys=True)),
                                  "checks": sorted(checks, key=lambda item: json.dumps(item, sort_keys=True)),
                                  "indexes": sorted(indexes, key=lambda item: item["name"])}
    return result


